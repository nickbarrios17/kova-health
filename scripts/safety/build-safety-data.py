"""
Builds the Ciclismo safety data (docs/ciclismo.md, «Zonas inseguras») as a SQL migration.

Inputs (download them first; URLs in docs/ciclismo.md):
  - CABA crime map, one CSV per year (BA Data, CC BY 2.5 AR): delitos_YYYY.csv
    Each row is one event with its point. We count, per ~275 m grid cell and per year:
      robos  = tipo «Robo» except car theft, robos_noche = the same between 20 h and 6 h,
      choques = «Vialidad» (people hurt or killed in traffic crashes).
  - SNIC by department, yearly (Ministerio de Seguridad): snic-departamentos-anual.csv
    Robbery rate per 100,000 people for each partido of Buenos Aires province.

Usage:
  python -I scripts/safety/build-safety-data.py --caba delitos_2024.csv delitos_2025.csv \
      --snic snic-departamentos-anual.csv --snic-year 2024 --out supabase/migrations/<ts>_safety_data.sql
"""
import argparse, csv, collections, math

# Grid shared with the bike-route function (GRID there): cell = floor((lat-LAT0)/DLAT):floor((lng-LNG0)/DLNG).
LAT0, LNG0, DLAT, DLNG = -34.75, -58.55, 0.0025, 0.003

# The 24 partidos of the conurbano (INDEC codes), the comparison base for the province data.
CONURBANO = {
    '06028', '06035', '06091', '06260', '06270', '06274', '06371', '06408', '06410', '06412', '06427', '06434',
    '06490', '06515', '06539', '06560', '06568', '06658', '06749', '06756', '06760', '06805', '06840', '06861',
}
ROBOS_SNIC = {'15', '16'}  # robos, and robos agravados por lesiones o muerte (not attempts)
# SNIC codes that differ from the INDEC codes the georef API answers with.
SNIC_TO_GEOREF = {'06058': '06658', '06217': '06218'}


def cell_of(lat, lng):
    return f'{math.floor((lat - LAT0) / DLAT)}:{math.floor((lng - LNG0) / DLNG)}'


def levels(values, high_q, mid_q):
    """Level 2 for the top `high_q` share of cells with events, 1 for the next up to `mid_q`."""
    xs = sorted(v for v in values if v > 0)
    if not xs:
        return lambda v: 0
    hi = xs[max(0, int(len(xs) * (1 - high_q)) - 1)]
    mid = xs[max(0, int(len(xs) * (1 - mid_q)) - 1)]
    return lambda v: 2 if v >= hi and v > 0 else 1 if v >= mid and v > 0 else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--caba', nargs='+', required=True)
    ap.add_argument('--snic', required=True)
    ap.add_argument('--snic-year', default='2024')
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    robos, noche, choques = collections.Counter(), collections.Counter(), collections.Counter()
    years = set()
    for path in a.caba:
        for r in csv.DictReader(open(path, encoding='utf-8-sig')):
            try:
                lat, lng = float(r['latitud']), float(r['longitud'])
            except (TypeError, ValueError):
                continue
            if not (-34.71 < lat < -34.52 and -58.54 < lng < -58.33):
                continue  # outside the city or a bad point
            years.add(r['anio'])
            n = int(r.get('cantidad') or 1)
            k = cell_of(lat, lng)
            if r['tipo'] == 'Robo' and r['subtipo'] != 'Robo automotor':
                robos[k] += n
                try:
                    h = int(r['franja'])
                except (TypeError, ValueError):
                    h = 12
                if h >= 20 or h < 6:
                    noche[k] += n
            elif r['tipo'] == 'Vialidad':
                choques[k] += n
    ny = max(1, len(years))
    cells = set(robos) | set(choques)
    robo_lvl = levels([robos[k] for k in cells], 0.10, 0.30)
    choque_lvl = levels([choques[k] for k in cells], 0.08, 0.25)

    # Province partidos: robbery rate in the chosen year.
    rate = collections.defaultdict(float)
    name = {}
    for r in csv.DictReader(open(a.snic, encoding='utf-8-sig'), delimiter=';'):
        if r['anio'] != a.snic_year or r['provincia_id'] != '06' or r['codigo_delito_snic_id'] not in ROBOS_SNIC:
            continue
        dep = SNIC_TO_GEOREF.get(r['departamento_id'], r['departamento_id'])
        if dep == '06999':
            continue  # «sin determinar»
        v = (r['tasa_hechos'] or '0').replace(',', '.')
        try:
            rate[dep] += float(v) if v != 'NA' else 0.0
        except ValueError:
            pass
        name[dep] = r['departamento_nombre']
    base = [rate[d] for d in CONURBANO if d in rate]
    avg = sum(base) / len(base) if base else 0.0

    def p_level(v):
        return 2 if avg and v >= avg * 1.3 else 1 if avg and v >= avg else 0

    q = lambda s: "'" + s.replace("'", "''") + "'"
    out = [
        '-- Generated by scripts/safety/build-safety-data.py; do not edit by hand. Sources and method in docs/ciclismo.md.',
        f'-- CABA crime map years: {", ".join(sorted(years))}. SNIC partidos year: {a.snic_year}. Conurbano robbery rate average: {avg:.1f} per 100,000.',
        'delete from public.safety_cells;',
        'delete from public.safety_partidos;',
    ]
    rows = []
    for k in sorted(cells):
        i, j = map(int, k.split(':'))
        lat = LAT0 + (i + 0.5) * DLAT
        lng = LNG0 + (j + 0.5) * DLNG
        rows.append(f"({q(k)},{lat:.5f},{lng:.5f},{robos[k] / ny:.1f},{noche[k] / ny:.1f},{choques[k] / ny:.1f},{robo_lvl(robos[k])},{choque_lvl(choques[k])})")
    for n in range(0, len(rows), 500):
        out.append('insert into public.safety_cells (cell, lat, lng, robos, robos_noche, choques, robo_level, choque_level) values\n' + ',\n'.join(rows[n:n + 500]) + ';')
    prow = [f"({q(d)},{q(name[d])},{rate[d]:.1f},{p_level(rate[d])},{int(a.snic_year)},{'true' if d in CONURBANO else 'false'})" for d in sorted(rate)]
    out.append('insert into public.safety_partidos (id, name, robos_rate, level, year, conurbano) values\n' + ',\n'.join(prow) + ';')
    out.append(f"insert into public.safety_meta (key, value) values ('sources', {q('{' + chr(34) + 'caba_years' + chr(34) + ': [' + ','.join(sorted(years)) + '], ' + chr(34) + 'snic_year' + chr(34) + ': ' + a.snic_year + ', ' + chr(34) + 'conurbano_avg_rate' + chr(34) + ': ' + f'{avg:.1f}' + '}')}::jsonb)")
    out[-1] += " on conflict (key) do update set value = excluded.value;"
    open(a.out, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    hi = sum(1 for k in cells if robo_lvl(robos[k]) == 2)
    print(f'{len(cells)} cells ({hi} with many robberies), {len(rate)} partidos, conurbano avg {avg:.1f}')


if __name__ == '__main__':
    main()
