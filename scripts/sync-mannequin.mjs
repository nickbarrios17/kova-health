// Copies the 3D mannequin (apps/web/public/mannequin.js, the source of truth) into the phone app as
// a string, for the WebView in apps/mobile/src/MannequinView.tsx. Run after changing mannequin.js:
//   node scripts/sync-mannequin.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../apps/web/public/mannequin.js', import.meta.url), 'utf8');
if (/<\/script/i.test(src)) throw new Error('mannequin.js must not contain "</script" (it is inlined in HTML)');
const out = `// Generated by scripts/sync-mannequin.mjs from apps/web/public/mannequin.js. Do not edit.\nexport const MANNEQUIN_JS = ${JSON.stringify(src)};\n`;
writeFileSync(new URL('../apps/mobile/src/mannequinSource.ts', import.meta.url), out);
console.log('apps/mobile/src/mannequinSource.ts', out.length, 'bytes');
